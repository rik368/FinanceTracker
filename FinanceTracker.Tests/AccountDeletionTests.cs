    [Fact]
    public async Task DeleteAccountRemovesAllMonthsAndIdentityDependentsButPreservesOtherOwner()
    {
        using var client = Client();
        using var other = Client();
        var email = await Register(client);
        var otherEmail = await Register(other);
        using var scope = factory.Services.CreateScope();
        var users = scope.ServiceProvider.GetRequiredService<UserManager<ApplicationUser>>();
        var user = (await users.FindByEmailAsync(email))!;
        var neighbour = (await users.FindByEmailAsync(otherEmail))!;
        await SeedDeletionData(user.Id);
        await SeedDeletionData(neighbour.Id);
        await users.AddClaimAsync(user, new System.Security.Claims.Claim("test", "value"));
        await users.AddLoginAsync(user, new UserLoginInfo("test", Guid.NewGuid().ToString(), "Test"));
        await users.SetAuthenticationTokenAsync(user, "test", "token", "value");
        var response = await Submit(client, "/Account/Manage/DeletePersonalData", "delete-user", new() { ["Input.Password"] = Password });
        Assert.Equal(HttpStatusCode.Redirect, response.StatusCode);
        await AssertDeletionData(user.Id, 0);
        await AssertDeletionData(neighbour.Id, 2);
        using var check = factory.Services.CreateScope();
        var identity = check.ServiceProvider.GetRequiredService<ApplicationDbContext>();
        Assert.False(await identity.Users.AnyAsync(x => x.Id == user.Id));
        Assert.False(await identity.UserClaims.AnyAsync(x => x.UserId == user.Id));
        Assert.False(await identity.UserLogins.AnyAsync(x => x.UserId == user.Id));
        Assert.False(await identity.UserTokens.AnyAsync(x => x.UserId == user.Id));
        Assert.True(await identity.Users.AnyAsync(x => x.Id == neighbour.Id));
        Assert.Equal(HttpStatusCode.Redirect, (await client.GetAsync("/exports/transactions?month=2026-11")).StatusCode);
        Assert.Contains("Invalid login attempt", await (await Login(client, email, Password)).Content.ReadAsStringAsync());
        var dbFactory = check.ServiceProvider.GetRequiredService<IDbContextFactory<FinanceDb>>();
        await Assert.ThrowsAsync<DbUpdateException>(() => new Ledger(dbFactory, new OwnerState(user.Id)).SaveAsync(new CategoryInput { Name = "Stale tab" }));
        await Register(client, email);
        var replacement = (await check.ServiceProvider.GetRequiredService<UserManager<ApplicationUser>>().FindByEmailAsync(email))!;
        Assert.NotEqual(user.Id, replacement.Id);
        await AssertDeletionData(replacement.Id, 0);
    }

    [Fact]
    public async Task IncorrectPasswordPreservesAccountAndAllFinancialData()
    {
        using var client = Client();
        var email = await Register(client);
        using var scope = factory.Services.CreateScope();
        var user = (await scope.ServiceProvider.GetRequiredService<UserManager<ApplicationUser>>().FindByEmailAsync(email))!;
        await SeedDeletionData(user.Id);
        var response = await Submit(client, "/Account/Manage/DeletePersonalData", "delete-user", new() { ["Input.Password"] = "Incorrect2026!" });
        Assert.Contains("Incorrect password", await response.Content.ReadAsStringAsync());
        await AssertDeletionData(user.Id, 2);
        Assert.True(await scope.ServiceProvider.GetRequiredService<ApplicationDbContext>().Users.AnyAsync(x => x.Id == user.Id));
    }

    [Fact]
    public async Task FailureDuringIdentityDeletionRollsBackFinanceAndAllowsRetry()
    {
        using var client = Client();
        var email = await Register(client);
        using var scope = factory.Services.CreateScope();
        var user = (await scope.ServiceProvider.GetRequiredService<UserManager<ApplicationUser>>().FindByEmailAsync(email))!;
        await SeedDeletionData(user.Id);
        var identity = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();
        // User ID is generated by Identity, never an externally supplied SQL fragment.
        var trigger = "FailDelete" + Guid.NewGuid().ToString("N");
#pragma warning disable EF1002 // Test-only DDL: generated identifier and escaped generated user ID.
        await identity.Database.ExecuteSqlRawAsync($"CREATE TRIGGER {trigger} BEFORE DELETE ON AspNetUsers WHEN OLD.Id = '{user.Id.Replace("'", "''")}' BEGIN SELECT RAISE(ABORT, 'Injected failure'); END;");
        try
        {
            var response = await Submit(client, "/Account/Manage/DeletePersonalData", "delete-user", new() { ["Input.Password"] = Password });
            Assert.Contains("No changes were saved", await response.Content.ReadAsStringAsync());
            await AssertDeletionData(user.Id, 2);
            Assert.True(await identity.Users.AnyAsync(x => x.Id == user.Id));
        }
        finally { await identity.Database.ExecuteSqlRawAsync($"DROP TRIGGER {trigger}"); }
#pragma warning restore EF1002
        Assert.Equal(HttpStatusCode.Redirect, (await Submit(client, "/Account/Manage/DeletePersonalData", "delete-user", new() { ["Input.Password"] = Password })).StatusCode);
        await AssertDeletionData(user.Id, 0);
    }

