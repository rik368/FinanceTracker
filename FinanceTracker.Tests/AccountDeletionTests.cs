    [Fact]
    public async Task StaleIdentityVersionRollsBackDeletion()
    {
        using var client = Client();
        var email = await Register(client);
        using var scope = factory.Services.CreateScope();
        var user = (await scope.ServiceProvider.GetRequiredService<UserManager<ApplicationUser>>().FindByEmailAsync(email))!;
        await SeedDeletionData(user.Id);
        user.ConcurrencyStamp = "stale";
        await Assert.ThrowsAsync<DbUpdateConcurrencyException>(() => scope.ServiceProvider.GetRequiredService<AccountDeletion>().DeleteAsync(user));
        await AssertDeletionData(user.Id, 2);
    }

    private async Task SeedDeletionData(string owner)
    {
        var ledger = new Ledger(factory.Services.GetRequiredService<IDbContextFactory<FinanceDb>>(), new OwnerState(owner));
        await ledger.SaveAsync(new CategoryInput { Name = "Expenses" });
        var month = new DateOnly(2026, 11, 1);
        var category = Assert.Single((await ledger.ReadAsync(month)).Categories);
        foreach (var date in new[] { month, month.AddMonths(-6) })
        {
            await ledger.SaveAsync(new TransactionInput { CategoryId = category.Id, Date = date, Amount = 12.34m });
            await ledger.SaveAsync(new BudgetInput { CategoryId = category.Id, Amount = 100m }, date);
        }
    }

    private async Task AssertDeletionData(string owner, int count)
    {
        await using var db = await factory.Services.GetRequiredService<IDbContextFactory<FinanceDb>>().CreateDbContextAsync();
        Assert.Equal(count, await db.Transactions.CountAsync(x => x.Owner == owner));
        Assert.Equal(count, await db.Budgets.CountAsync(x => x.Owner == owner));
        Assert.Equal(count == 0 ? 0 : 1, await db.Categories.CountAsync(x => x.Owner == owner));
    }
